"""Generates lib/features/convert/layout/font_metrics_data.dart: advance
widths (per 1000 em) of characters U+0020..U+00FF and a few punctuation
marks for Arial-, Times- and Courier-compatible fonts, taken from the
metric-compatible Liberation fonts (SIL OFL). Run: python3 tool/gen_font_metrics.py"""
import sys
from fontTools.ttLib import TTFont

D = '/usr/share/fonts/truetype/liberation/'
FONTS = {
    'sans': 'LiberationSans-Regular.ttf', 'sansBold': 'LiberationSans-Bold.ttf',
    'sansItalic': 'LiberationSans-Italic.ttf', 'sansBoldItalic': 'LiberationSans-BoldItalic.ttf',
    'serif': 'LiberationSerif-Regular.ttf', 'serifBold': 'LiberationSerif-Bold.ttf',
    'serifItalic': 'LiberationSerif-Italic.ttf', 'serifBoldItalic': 'LiberationSerif-BoldItalic.ttf',
}
EXTRA = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x20B9, 0x2026]
codes = list(range(0x20, 0x100)) + EXTRA
out = ['// GENERATED by tool/gen_font_metrics.py from the Liberation fonts (SIL OFL 1.1),',
       '// which are metric-compatible with Arial and Times New Roman. Do not edit.',
       '', 'const fontCodes = <int>[' + ', '.join(str(c) for c in codes) + '];', '']
for key, f in FONTS.items():
    t = TTFont(D + f)
    upm = t['head'].unitsPerEm
    cmap = t.getBestCmap()
    hmtx = t['hmtx'].metrics
    asc = t['hhea'].ascent; desc = -t['hhea'].descent
    ws = []
    for c in codes:
        g = cmap.get(c)
        ws.append(round(hmtx[g][0] * 1000 / upm) if g else 500)
    out.append(f'const {key}Widths = <int>[' + ', '.join(map(str, ws)) + '];')
    out.append(f'const {key}AscentDescent = ({round(asc*1000/upm)}, {round(desc*1000/upm)});')
open(sys.argv[1] if len(sys.argv) > 1 else 'lib/features/convert/layout/font_metrics_data.dart', 'w').write('\n'.join(out) + '\n')
